#!/usr/bin/env bash
# Scoped Linux user-service lifecycle. No sudo, linger changes, PID adoption,
# credential copying, or implicit replacement of an existing unit.
set -euo pipefail
fail() { printf 'niffler-server: %s\n' "$*" >&2; exit 1; }
[[ $# == 2 ]] || fail 'usage: server.sh install|start|status|logs|stop|linger <root>'
action=$1
case "$action" in install|start|status|logs|stop|linger) ;; *) fail "unknown action: $action" ;; esac
[[ $(uname -s) == Linux ]] || fail 'user services require Linux/systemd'
root=$(cd -- "$2" && pwd -P) || fail 'root does not exist'
# Restrict systemd syntax rather than interpolating unescaped specifiers/quotes.
[[ "$root" =~ ^/[a-zA-Z0-9_./-]+$ && "$HOME" =~ ^/[a-zA-Z0-9_./-]+$ ]] || fail 'service root and HOME must contain only letters, digits, /, ., _, -'
[[ -f "$root/niffler.nimble" && -x "$root/var/bin/niffler" ]] || fail 'not a built Niffler root; run make build first'
key=$(printf '%s' "$root" | sha256sum)
unit="niffler-${key:0:16}.service"
unitDir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
path="$unitDir/$unit"
render() {
  printf '%s\n' '# Generated by Niffler server.sh; exact root-scoped contract.' \
    '[Unit]' 'Description=Niffler persistent server' '' '[Service]' \
    'Type=simple' "WorkingDirectory=$root" "Environment=NIF_ROOT=$root" \
    'Environment=NIF_NATS_URL=' 'Environment=NIF_NATS_SPAWN=1' \
    'Environment=NIF_AUTOSTART=0' 'Environment=NIF_AUTO_APPROVE=0' \
    "Environment=PATH=$HOME/.nimble/bin:/usr/local/bin:/usr/bin:/bin" \
    "ExecStart=$root/var/bin/niffler" 'Restart=on-failure' 'RestartSec=3' \
    'StandardInput=null' 'KillMode=control-group' 'TimeoutStopSec=30' \
    '' '[Install]' 'WantedBy=default.target'
}
verify() {
  [[ -f "$path" && ! -L "$path" ]] || fail "unit missing or symlinked: $path"
  cmp -s "$path" <(render) || fail "refusing conflicting unit: $path (no overwrite or adoption)"
}
linger() {
  local state
  state=$(loginctl show-user "$(id -un)" -p Linger --value 2>/dev/null) || state=unknown
  printf 'niffler-server: linger=%s\n' "$state"
  if [[ "$state" != yes ]]; then
    printf '%s\n' 'Logout/reboot persistence is not guaranteed. Ask your administrator about loginctl enable-linger; this helper never changes it.'
  fi
}
case "$action" in
  install)
    command -v systemctl >/dev/null || fail 'systemctl is required'
    systemctl --user show-environment >/dev/null || fail 'user systemd manager unavailable'
    mkdir -p "$unitDir"
    if [[ -e "$path" || -L "$path" ]]; then
      verify
    else
      # noclobber protects a racing installer; never replace another unit.
      (umask 077; set -o noclobber; render > "$path") || fail "cannot create $path"
    fi
    systemctl --user daemon-reload
    systemctl --user enable "$unit"
    printf 'niffler-server: installed %s (not started)\n' "$unit"
    linger
    ;;
  linger) linger ;;
  *)
    verify
    case "$action" in
      logs) journalctl --user -u "$unit" -n 100 --no-pager ;;
      *) systemctl --user "$action" "$unit" ;;
    esac
    ;;
esac
