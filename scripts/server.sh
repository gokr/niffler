#!/usr/bin/env bash
# Scoped Linux user-service lifecycle. No sudo, linger changes, PID adoption,
# credential copying, or implicit replacement of an existing unit.
set -euo pipefail
fail() { printf 'niffler-server: %s\n' "$*" >&2; exit 1; }
[[ $# == 2 ]] || fail 'usage: server.sh install|refresh|start|status|logs|stop|linger|persist <root>'
action=$1
case "$action" in install|refresh|start|status|logs|stop|linger|persist) ;; *) fail "unknown action: $action" ;; esac
[[ $(uname -s) == Linux ]] || fail 'user services require Linux/systemd'
root=$(cd -- "$2" && pwd -P) || fail 'root does not exist'
# Restrict systemd syntax rather than interpolating unescaped specifiers/quotes.
[[ "$root" =~ ^/[a-zA-Z0-9_./-]+$ && "$HOME" =~ ^/[a-zA-Z0-9_./-]+$ ]] || fail 'service root and HOME must contain only letters, digits, /, ., _, -'
[[ -f "$root/niffler.nimble" && -x "$root/var/bin/niffler" ]] || fail 'not a built Niffler root; run make build first'
key=$(printf '%s' "$root" | sha256sum)
unit="niffler-${key:0:16}.service"
unitDir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
path="$unitDir/$unit"
render() {
  # Restart=always, not on-failure: a resident server must come back from a
  # crash, an OOM kill or a clean exit caused by a stray SIGTERM (`make down` in
  # the guest, a killed PID) — that last case is what on-failure leaves dead.
  # systemd suppresses the restart for an explicit `systemctl --user stop`
  # (server.sh stop), so an operator's decision still sticks.
  printf '%s\n' '# Generated by Niffler server.sh; exact root-scoped contract.' \
    '[Unit]' 'Description=Niffler persistent server' '' '[Service]' \
    'Type=simple' "WorkingDirectory=$root" "Environment=NIF_ROOT=$root" \
    'Environment=NIF_NATS_URL=' 'Environment=NIF_NATS_SPAWN=1' \
    'Environment=NIF_AUTOSTART=0' 'Environment=NIF_AUTO_APPROVE=0' \
    'Environment=NIF_APPROVALS_DEFAULT=auto' \
    "Environment=PATH=$HOME/.nimble/bin:/usr/local/bin:/usr/bin:/bin" \
    "ExecStart=$root/var/bin/niffler" 'Restart=always' 'RestartSec=3' \
    'StandardInput=null' 'KillMode=control-group' 'TimeoutStopSec=30' \
    '' '[Install]' 'WantedBy=default.target'
}
verify() {
  [[ -f "$path" && ! -L "$path" ]] || fail "unit missing or symlinked: $path"
  cmp -s "$path" <(render) || fail "refusing conflicting unit: $path (no overwrite or adoption)"
}
linger() {
  local state
  state=$(loginctl show-user "$(id -un)" -p Linger --value 2>/dev/null) || state=unknown
  printf 'niffler-server: linger=%s\n' "$state"
  if [[ "$state" != yes ]]; then
    printf '%s\n' 'Logout/reboot persistence is not guaranteed. Ask your administrator about loginctl enable-linger; this helper never changes it.'
  fi
}
# Replace a unit this root previously wrote. A checkout's render() is the unit
# contract, so a change to it (a new restart policy, a new Environment= line)
# makes every earlier install refuse — deliberately, since silently adopting a
# unit with unknown content is how a foreign service gets inherited. Refresh is
# the explicit way forward: it proves the file is ours, stops the old process,
# rewrites and re-enables, and never starts.
refresh() {
  command -v systemctl >/dev/null || fail 'systemctl is required'
  [[ -f "$path" && ! -L "$path" ]] || fail "no unit installed for this root: $path (run install)"
  head -n 1 "$path" | grep -qx '# Generated by Niffler server.sh; exact root-scoped contract.' ||
    fail "refusing to replace a unit this checkout did not write: $path"
  local wasEnabled=no
  if systemctl --user is-enabled "$unit" >/dev/null 2>&1; then wasEnabled=yes; fi
  # The replaced unit must not leave the old process serving the previous build.
  systemctl --user stop "$unit" >/dev/null 2>&1 || true
  rm -f "$path"
  (umask 077; set -o noclobber; render > "$path") || fail "cannot create $path"
  systemctl --user daemon-reload
  if [[ "$wasEnabled" == yes ]]; then
    systemctl --user enable "$unit" >/dev/null
  else
    printf '%s\n' 'niffler-server: unit was not enabled; leaving it disabled (run install to enable)'
  fi
  printf 'niffler-server: refreshed %s (not started)\n' "$unit"
  linger
}
# Readiness report for "this instance stays up across crashes and reboots".
# Three things keep a remote instance reachable and they fail independently:
# the guest boot policy (invisible from inside), linger, and an enabled unit.
# This helper can prove the two guest-side ones and that the unit still matches
# this checkout; a stale unit is exactly how an instance silently loses a fix.
persist() {
  local failed=0 virt enabled active policy state
  printf 'niffler-server: root=%s\n' "$root"
  # A user-manager query needs the session bus. `incus shell box` (or any
  # non-login `su`) has no logind session, so XDG_RUNTIME_DIR and
  # DBUS_SESSION_BUS_ADDRESS are unset and every systemctl --user call returns
  # "Failed to connect to bus". That is a property of THIS SHELL, not of the
  # instance — the unit can be perfectly persistent while this process cannot
  # see it. Treating the empty answer as "disabled/inactive" reported
  # "NOT persistent yet" and told the operator to reinstall a healthy service,
  # which is worse than saying nothing.
  if ! systemctl --user show-environment >/dev/null 2>&1; then
    printf '%s\n' 'niffler-server: cannot reach the systemd user manager from this shell'
    printf '%s\n' '  (no XDG_RUNTIME_DIR/DBUS_SESSION_BUS_ADDRESS — a non-login shell: `incus shell`, or `su` without a logind session)'
    printf '%s\n' '  retry from a real login session, or export:'
    printf '%s\n' "    XDG_RUNTIME_DIR=/run/user/$(id -u)"
    printf '%s\n' "    DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/$(id -u)/bus"
    printf '%s\n' 'niffler-server: UNKNOWN — the unit state could not be read (this is not a verdict)'
    return 2
  fi
  if [[ ! -f "$path" || -L "$path" ]]; then
    printf 'niffler-server: unit=missing %s\n  run: scripts/server.sh install %s\n' "$path" "$root"
    return 1
  fi
  if cmp -s "$path" <(render); then
    printf 'niffler-server: unit=current\n'
  else
    printf 'niffler-server: unit=stale (written by an older scripts/server.sh)\n  run: scripts/server.sh refresh %s\n' "$root"
    failed=1
  fi
  enabled=$(systemctl --user is-enabled "$unit" 2>/dev/null || true)
  printf 'niffler-server: enabled=%s\n' "${enabled:-unknown}"
  if [[ "$enabled" != enabled ]]; then
    printf '  run: scripts/server.sh install %s\n' "$root"
    failed=1
  fi
  active=$(systemctl --user is-active "$unit" 2>/dev/null || true)
  policy=$(systemctl --user show "$unit" -p Restart --value 2>/dev/null || true)
  printf 'niffler-server: active=%s restart=%s\n' "${active:-unknown}" "${policy:-unknown}"
  if [[ "$active" != active ]]; then
    printf '  run: scripts/server.sh start %s\n' "$root"
    failed=1
  fi
  if [[ "$policy" != always ]]; then
    printf 'niffler-server: restart policy does not survive a clean exit (stray SIGTERM)\n  run: scripts/server.sh refresh %s\n' "$root"
    failed=1
  fi
  state=$(loginctl show-user "$(id -un)" -p Linger --value 2>/dev/null) || state=unknown
  printf 'niffler-server: linger=%s\n' "$state"
  if [[ "$state" == unknown ]]; then
    printf '%s\n' '  cannot read linger from here (no logind session); check `loginctl show-user' "$(id -un)" '-p Linger` in a login shell'
    failed=1
  elif [[ "$state" != yes ]]; then
    printf '%s\n' '  run (as this instance administrator): loginctl enable-linger; a user unit without linger is stopped at logout'
    failed=1
  fi
  # Host boot policy is outside the guest: a container or VM that never starts
  # runs no systemd, so everything above is moot after a host reboot. Report
  # what to verify instead of claiming a reboot survives — this helper cannot
  # read the management host, and a set policy must not look like a task left to
  # do.
  virt=$(systemd-detect-virt 2>/dev/null || true)
  case "$virt" in
    incus|lxc|lxc-lxd|systemd-nspawn)
      printf 'niffler-server: boot=container (%s) - verify on the management host: incus config get <container> boot.autostart (expected true)\n' "$virt" ;;
    kvm|qemu|none|"")
      printf 'niffler-server: boot=%s - verify the host starts this VM (macOS: limactl autostart; Linux: a host unit)\n' "${virt:-none}" ;;
    *)
      printf 'niffler-server: boot=%s - verify host boot policy separately\n' "$virt" ;;
  esac
  if [[ "$failed" != 0 ]]; then
    printf '%s\n' 'niffler-server: NOT persistent yet (see the lines above)'
    return 1
  fi
  printf '%s\n' 'niffler-server: guest-side persistence OK (unit current, enabled, active, restart=always, linger=yes)'
}
case "$action" in
  install)
    command -v systemctl >/dev/null || fail 'systemctl is required'
    systemctl --user show-environment >/dev/null || fail 'user systemd manager unavailable'
    mkdir -p "$unitDir"
    if [[ -e "$path" || -L "$path" ]]; then
      verify
    else
      # noclobber protects a racing installer; never replace another unit.
      (umask 077; set -o noclobber; render > "$path") || fail "cannot create $path"
    fi
    systemctl --user daemon-reload
    systemctl --user enable "$unit"
    printf 'niffler-server: installed %s (not started)\n' "$unit"
    linger
    ;;
  refresh) refresh ;;
  persist) persist ;;
  linger) linger ;;
  *)
    verify
    case "$action" in
      logs) journalctl --user -u "$unit" -n 100 --no-pager ;;
      *) systemctl --user "$action" "$unit" ;;
    esac
    ;;
esac
